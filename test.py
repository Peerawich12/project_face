import cv2

# ลองเปลี่ยนเลขในวงเล็บ: 
# 0 = กล้องหลักของคอมพิวเตอร์ (Camera_PC)
# 1 = กล้อง Webcam ที่เสียบ USB
# cv2.CAP_DSHOW ช่วยให้กล้องเปิดเร็วขึ้นบน Windows
cap = cv2.VideoCapture(1, cv2.CAP_DSHOW)

# 1. เช็คความพร้อมของกล้องก่อนเริ่มทำงาน
if not cap.isOpened():
    print("❌ ไม่สามารถเปิดกล้องได้! กรุณาตรวจสอบสายเสียบ หรือลองเปลี่ยนเลข 0 เป็น 1")
    exit()

print("✅ เปิดกล้องสำเร็จ! (กดปุ่ม 'q' บนคีย์บอร์ดเพื่อปิดหน้าต่างกล้อง)")

while True:
    # 2. อ่านเฟรมภาพจากกล้อง
    ret, frame = cap.read()
    
    # เช็คว่าภาพที่อ่านได้สมบูรณ์หรือไม่
    if not ret:
        print("❌ ไม่สามารถดึงภาพจากกล้องได้ (Frame ว่างเปล่า)")
        break

    # 3. แสดงผลภาพบนหน้าจอ
    cv2.imshow("Webcam Test", frame)

    # 4. ตั้งค่าปุ่มกดปิด: ถ้ากดปุ่ม 'q' ที่คีย์บอร์ดจะออกจากลูปทันที
    if cv2.waitKey(1) & 0xFF == ord('q'):
        break

# 5. คืนหน่วยความจำและปิดหน้าต่างทั้งหมดอย่างปลอดภัย
cap.release()
cv2.destroyAllWindows()
print("🔒 ปิดระบบกล้องเรียบร้อย")
